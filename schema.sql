-- Open Items: database setup for Supabase
-- Paste this whole file into Supabase > SQL Editor > New query, then click Run.
-- Safe to run once on a new project. It creates the tables, the security rules,
-- and the five starting section headers.

-- ---------- People ----------
-- One row per login. Created automatically when you add a user in
-- Authentication > Users. Each person can change their own display name in the app.
create table public.profiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  name       text not null,
  email      text,
  active     boolean not null default true,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, name, email)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data->>'name', ''), initcap(translate(split_part(new.email, '@', 1), '._', '  '))),
    new.email
  )
  on conflict (id) do nothing;
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------- Jobs ----------
create table public.jobs (
  id         text primary key check (id ~ '^[A-Za-z0-9-]{1,12}$'),
  name       text not null,
  archived   boolean not null default false,
  created_at timestamptz not null default now()
);

-- ---------- Section headers (shared by every job) ----------
create table public.sections (
  id         bigint generated by default as identity primary key,
  name       text not null,
  sort       integer not null default 0,
  created_at timestamptz not null default now()
);

-- ---------- Items ----------
create table public.items (
  id          bigint generated by default as identity primary key,
  job_id      text not null references public.jobs(id) on update cascade on delete restrict,
  section_id  bigint not null references public.sections(id) on delete restrict,
  text        text not null check (length(trim(text)) > 0),
  assignee    uuid references public.profiles(id) on delete set null,
  due         date,
  critical    boolean not null default false,
  note        text not null default '',
  done        boolean not null default false,
  done_by     uuid references public.profiles(id) on delete set null,
  done_at     timestamptz,
  created_by  uuid references public.profiles(id) on delete set null default auth.uid(),
  created_at  timestamptz not null default now(),
  updated_by  uuid references public.profiles(id) on delete set null default auth.uid(),
  updated_at  timestamptz not null default now()
);
create index items_job_idx on public.items (job_id);
create index items_assignee_idx on public.items (assignee) where not done;
create index items_updated_idx on public.items (updated_at);

-- ---------- Job notes (one notes page per job) ----------
create table public.job_notes (
  job_id     text primary key references public.jobs(id) on update cascade on delete cascade,
  body       text not null default '',
  updated_by uuid references public.profiles(id) on delete set null default auth.uid(),
  updated_at timestamptz not null default now()
);

-- Stamp who changed a row and when, on every update.
create or replace function public.touch_row()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  new.updated_by := coalesce(auth.uid(), new.updated_by);
  return new;
end $$;

create trigger items_touch before update on public.items
  for each row execute function public.touch_row();
create trigger job_notes_touch before update on public.job_notes
  for each row execute function public.touch_row();

-- ---------- Security ----------
-- Only signed-in users can see or change anything. Everyone signed in sees
-- every job (internal team app). People can only edit their own profile.
alter table public.profiles  enable row level security;
alter table public.jobs      enable row level security;
alter table public.sections  enable row level security;
alter table public.items     enable row level security;
alter table public.job_notes enable row level security;

create policy "team reads profiles"   on public.profiles for select to authenticated using (true);
create policy "edit own profile"      on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

create policy "team reads jobs"       on public.jobs for select to authenticated using (true);
create policy "team adds jobs"        on public.jobs for insert to authenticated with check (true);
create policy "team edits jobs"       on public.jobs for update to authenticated using (true) with check (true);

create policy "team reads sections"   on public.sections for select to authenticated using (true);
create policy "team adds sections"    on public.sections for insert to authenticated with check (true);
create policy "team edits sections"   on public.sections for update to authenticated using (true) with check (true);
create policy "team deletes sections" on public.sections for delete to authenticated using (true);

create policy "team reads items"      on public.items for select to authenticated using (true);
create policy "team adds items"       on public.items for insert to authenticated with check (true);
create policy "team edits items"      on public.items for update to authenticated using (true) with check (true);
create policy "team deletes items"    on public.items for delete to authenticated using (true);

create policy "team reads notes"      on public.job_notes for select to authenticated using (true);
create policy "team adds notes"       on public.job_notes for insert to authenticated with check (true);
create policy "team edits notes"      on public.job_notes for update to authenticated using (true) with check (true);

-- The public "anon" key in the web page gets nothing without a login.
revoke all on public.profiles, public.jobs, public.sections, public.items, public.job_notes from anon;
grant select, update on public.profiles to authenticated;
grant select, insert, update on public.jobs to authenticated;
grant select, insert, update, delete on public.sections, public.items to authenticated;
grant select, insert, update on public.job_notes to authenticated;

